async def test_linking_attaches_google_and_fills_an_empty_profile(
    http: AsyncClient,
    exchange: _Exchange,
    google_settings: Settings,
    db_session: AsyncSession,
) -> None:
    user = await _account(db_session, email="member@example.com")
    user_id = user.id
    headers = _bearer(user, google_settings)
    state, nonce = await _start(http, "/auth/identities/google/authorize", headers=headers)
    exchange.id_token = _id_token(nonce=nonce)

    response = await http.post(
        f"{API}/auth/identities/google/link",
        json={"code": "c", "state": state},
        headers=headers,
    )

    assert response.status_code == 200
    body = response.json()
    assert body["provider"] == "google"
    assert body["connected_at"]
    # Connecting is not signing in, so it has never been used to open a session.
    assert body["last_login_at"] is None
    # And it is emphatically not a session.
    assert "access_token" not in json.dumps(body)

    db_session.expire_all()
    reloaded = await db_session.get(User, user_id)
    assert reloaded is not None
    assert reloaded.avatar_url == GOOGLE_PICTURE
    assert reloaded.full_name == GOOGLE_NAME
    # Linking must not cost the account its password.
    assert reloaded.hashed_password == "not-a-real-hash"

    identities = await _identities(db_session)
    assert len(identities) == 1
    assert identities[0].user_id == user_id
    assert await _audit(db_session, AuditAction.GOOGLE_IDENTITY_LINKED)


async def test_a_login_flow_cannot_be_finished_at_the_link_endpoint(
    http: AsyncClient,
    exchange: _Exchange,
    google_settings: Settings,
    db_session: AsyncSession,
) -> None:
    """Flows carry their kind, so the weaker entry cannot feed the stronger one."""
    user = await _account(db_session, email="member@example.com")
    state, nonce = await _start(http, "/auth/google/authorize")
    exchange.id_token = _id_token(nonce=nonce)

    response = await http.post(
        f"{API}/auth/identities/google/link",
        json={"code": "c", "state": state},
        headers=_bearer(user, google_settings),
    )

    assert response.status_code == 401
    assert await _identities(db_session) == []


async def test_a_link_flow_started_by_somebody_else_is_refused(
    http: AsyncClient,
    exchange: _Exchange,
    google_settings: Settings,
    db_session: AsyncSession,
) -> None:
    """The binding is the account recorded when the flow began, not the token."""
    starter = await _account(db_session, email="starter@example.com")
    finisher = await _account(db_session, email="finisher@example.com")

    state, nonce = await _start(
        http,
        "/auth/identities/google/authorize",
        headers=_bearer(starter, google_settings),
    )
    exchange.id_token = _id_token(nonce=nonce)

    response = await http.post(
        f"{API}/auth/identities/google/link",
        json={"code": "c", "state": state},
        headers=_bearer(finisher, google_settings),
    )

    assert response.status_code == 401
    assert await _identities(db_session) == []


async def test_a_google_account_already_connected_elsewhere_is_refused(
    http: AsyncClient,
    exchange: _Exchange,
    google_settings: Settings,
    db_session: AsyncSession,
) -> None:
    """Moving an identity would walk somebody's sign-in method off their account."""
    owner = await _account(db_session, email="owner@example.com")
    db_session.add(
        FederatedIdentity(
            user_id=owner.id,
            provider=IdentityProvider.GOOGLE,
            provider_subject=SUBJECT,
        )
    )
    other = await _account(db_session, email="other@example.com")
    await db_session.flush()

    headers = _bearer(other, google_settings)
    state, nonce = await _start(http, "/auth/identities/google/authorize", headers=headers)
    exchange.id_token = _id_token(nonce=nonce)

    response = await http.post(
        f"{API}/auth/identities/google/link",
        json={"code": "c", "state": state},
        headers=headers,
    )

    assert response.status_code == 409
    identities = await _identities(db_session)
    assert len(identities) == 1
    assert identities[0].user_id == owner.id
    assert await _audit(db_session, AuditAction.GOOGLE_IDENTITY_LINK_FAILED)


