# --- Cross-cutting --------------------------------------------------------


async def test_no_response_ever_carries_google_material(
    http: AsyncClient,
    exchange: _Exchange,
    google_settings: Settings,
    db_session: AsyncSession,
) -> None:
    """The client secret, the code and the ID token stay on this side.

    Checked across every route in one place, because "no route leaks it" is the
    property, and asserting it per route invites the next route to be the one
    nobody checked.
    """
    user = await _account(db_session, email="member@example.com")
    headers = _bearer(user, google_settings)

    state, nonce = await _start(http, "/auth/google/authorize")
    exchange.id_token = _id_token(nonce=nonce)
    bodies = [
        (await http.post(f"{API}/auth/google/authorize")).text,
        (await http.post(f"{API}/auth/google/callback", json={"code": "c", "state": state})).text,
        (await http.post(f"{API}/auth/identities/google/authorize", headers=headers)).text,
        (
            await http.post(
                f"{API}/auth/identities/google/link",
                json={"code": "c", "state": "b" * 43},
                headers=headers,
            )
        ).text,
        (await http.delete(f"{API}/auth/identities/google", headers=headers)).text,
    ]

    secret = google_settings.google_client_secret
    assert secret is not None
    for body in bodies:
        assert secret not in body
        assert exchange.id_token not in body
        # The nonce and the PKCE verifier are server-side state; the authorize
        # responses carry a nonce inside the Google URL by design, so only the
        # verifier is checked here.
        for call in exchange.calls:
            assert call["code_verifier"] not in body


async def test_the_stored_flow_is_opaque(http: AsyncClient, google_app: FastAPI) -> None:
    """What is written to Redis names no account and no address."""
    state, _ = await _start(http, "/auth/google/authorize")

    stored = google_app.state.redis.client.values
    assert stored, "the flow was not written"
    for key, payload in stored.items():
        assert state in key
        decoded = json.dumps(json.loads(payload)) if payload.startswith("{") else payload
        assert GOOGLE_EMAIL not in decoded
        assert base64.b64encode(GOOGLE_EMAIL.encode()).decode() not in decoded
