async def test_authorize_is_open_and_returns_a_real_google_url(http: AsyncClient) -> None:
    """Unauthenticated by design: this is how somebody with no account starts."""
    response = await http.post(f"{API}/auth/google/authorize")

    assert response.status_code == 200
    body = response.json()
    assert set(body) == {"authorization_url", "expires_in"}
    assert body["expires_in"] > 0

    parts = urlsplit(body["authorization_url"])
    assert parts.scheme == "https"
    assert parts.netloc == "accounts.google.com"
    query = parse_qs(parts.query)
    assert query["client_id"] == [CLIENT_ID]
    assert query["redirect_uri"] == [REDIRECT_URI]
    assert query["response_type"] == ["code"]
    assert query["code_challenge_method"] == ["S256"]
    # The parameter that makes "no refresh token is ever stored" structural
    # rather than a rule somebody has to remember.
    assert query["access_type"] == ["online"]
    assert query["scope"] == ["openid email profile"]


