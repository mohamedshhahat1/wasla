async def test_unlinking_removes_the_identity_from_an_account_with_a_password(
    http: AsyncClient,
    google_settings: Settings,
    db_session: AsyncSession,
) -> None:
    user = await _account(db_session, email="member@example.com")
    db_session.add(
        FederatedIdentity(
            user_id=user.id,
            provider=IdentityProvider.GOOGLE,
            provider_subject=SUBJECT,
        )
    )
    await db_session.flush()

    response = await http.delete(
        f"{API}/auth/identities/google",
        headers=_bearer(user, google_settings),
    )

    assert response.status_code == 204
    assert not response.content
    assert await _identities(db_session) == []
    assert await _audit(db_session, AuditAction.GOOGLE_IDENTITY_UNLINKED)


async def test_unlinking_the_last_way_in_is_refused(
    http: AsyncClient,
    google_settings: Settings,
    db_session: AsyncSession,
) -> None:
    """A Google-only account has no password, so removing Google locks it out."""
    user = await _account(db_session, email=GOOGLE_EMAIL, hashed_password=None)
    db_session.add(
        FederatedIdentity(
            user_id=user.id,
            provider=IdentityProvider.GOOGLE,
            provider_subject=SUBJECT,
        )
    )
    await db_session.flush()

    response = await http.delete(
        f"{API}/auth/identities/google",
        headers=_bearer(user, google_settings),
    )

    assert response.status_code == 403
    assert len(await _identities(db_session)) == 1


