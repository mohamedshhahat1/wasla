"""The five Google endpoints, over HTTP, against a real database.

`test_google_profile.py` drives `GoogleAuthService` directly. That proves the
rules but says nothing about the layer above: whether the routes are mounted
where the matrix claims, whether the guards resolve, whether a refusal deep in
the service becomes the status code the API contract promises, and whether the
transaction the route opened is what ends up in PostgreSQL.

**Only Google's network is stubbed.** The verifier is the real one and does real
RS256 validation against a real key set, over tokens really signed by a real RSA
key - the same machinery `test_google_oidc.py` uses. The authorization URL is
built by the real client. The flow store, the service, the repositories, the
audit trail, the token issuer and the database are all real, and the state and
nonce are read back out of the store the way Google would carry them, rather
than invented by the test. What is replaced is exactly one method - the HTTPS
call to Google's token endpoint - because a test that needed real Google
credentials would be a test nobody can run.

This is the closest a suite can get to the browser flow without a Google client
id. It is **not** a substitute for one: no test here proves that Google accepts
this deployment's redirect URI, that the consent screen renders, or that a real
`sub` looks like what the model expects. See `docs/GOOGLE_OAUTH.md`.
"""

