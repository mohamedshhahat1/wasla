async def test_a_second_login_refreshes_the_profile_but_not_the_address(
    http: AsyncClient,
    exchange: _Exchange,
    db_session: AsyncSession,
) -> None:
    """Profile refresh over HTTP, including the address that must not move.

    The security half and the feature half in one test on purpose: the name and
    picture moving is what makes the address standing still a decision rather
    than the refresh silently not running.
    """
    state, nonce = await _start(http, "/auth/google/authorize")
    exchange.id_token = _id_token(nonce=nonce)
    await http.post(f"{API}/auth/google/callback", json={"code": "c", "state": state})

    moved_picture = "https://lh3.googleusercontent.com/a/second=s96-c"
    state, nonce = await _start(http, "/auth/google/authorize")
    exchange.id_token = _id_token(
        nonce=nonce,
        name="A Renamed Person",
        picture=moved_picture,
        email="somebody-elses@example.com",
    )
    second = await http.post(f"{API}/auth/google/callback", json={"code": "c2", "state": state})

    assert second.status_code == 200
    db_session.expire_all()

    user = await db_session.scalar(select(User).where(User.email == GOOGLE_EMAIL))
    assert user is not None
    assert user.full_name == "A Renamed Person"
    assert user.avatar_url == moved_picture
    assert user.email == GOOGLE_EMAIL

    # No account was created on the address the second token claimed, and no
    # second identity for the same subject.
    assert (
        await db_session.scalar(select(User).where(User.email == "somebody-elses@example.com"))
        is None
    )
    assert len(await _identities(db_session)) == 1


async def test_a_verified_google_address_never_claims_an_existing_account(
    http: AsyncClient,
    exchange: _Exchange,
    db_session: AsyncSession,
) -> None:
    """Collision refusal (ADR-049), over HTTP.

    Proving control of a mailbox is not proof of anything about an account
    registered under it. The refusal must be a 409 that signs nobody in, links
    nothing, and leaves the existing account's password untouched.
    """
    existing = await _account(db_session, email=GOOGLE_EMAIL, hashed_password="the-real-hash")
    # Read before the expire below: dereferencing an expired attribute on an
    # async session is a lazy load, which is an error rather than a query.
    existing_id = existing.id

    state, nonce = await _start(http, "/auth/google/authorize")
    exchange.id_token = _id_token(nonce=nonce)
    response = await http.post(f"{API}/auth/google/callback", json={"code": "c", "state": state})

    assert response.status_code == 409
    body = response.json()
    assert "access_token" not in json.dumps(body)

    db_session.expire_all()
    reloaded = await db_session.get(User, existing_id)
    assert reloaded is not None
    assert reloaded.hashed_password == "the-real-hash"
    assert reloaded.avatar_url is None
    assert await _identities(db_session) == []
    assert await _audit(db_session, AuditAction.GOOGLE_LOGIN_FAILED)


