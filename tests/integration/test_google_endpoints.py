def _bearer(user: User, settings: Settings) -> dict[str, str]:
    token, _ = create_access_token(
        settings=settings,
        subject=user.id,
        tenant_id=None,
        token_version=user.token_version,
    )
    return {"Authorization": f"Bearer {token}"}


async def _account(
    session: AsyncSession,
    *,
    email: str,
    # Not a credential: nothing verifies it. `login` only ever asks whether the
    # column is None, which is what distinguishes a Google-only account.
    hashed_password: str | None = "not-a-real-hash",  # noqa: S107
    is_active: bool = True,
) -> User:
    user = User(
        email=email,
        full_name="Chosen In Wasla",
        hashed_password=hashed_password,
        is_active=is_active,
    )
    session.add(user)
    await session.flush()
    return user


async def _start(http: AsyncClient, path: str, **kwargs) -> tuple[str, str]:
    """Run a real `authorize` request and return its `state` and `nonce`.

    Read out of the authorization URL the application built, not invented here:
    a test that made up its own state would be testing nothing about the store
    that has to recognise it later.
    """
    response = await http.post(f"{API}{path}", **kwargs)
    assert response.status_code == 200, response.text
    query = parse_qs(urlsplit(response.json()["authorization_url"]).query)
    return query["state"][0], query["nonce"][0]


async def _identities(session: AsyncSession) -> list[FederatedIdentity]:
    return list((await session.scalars(select(FederatedIdentity))).all())


async def _audit(session: AsyncSession, action: AuditAction) -> list[AuditLog]:
    return list((await session.scalars(select(AuditLog).where(AuditLog.action == action))).all())


