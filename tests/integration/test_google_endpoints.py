# Shaped like a real one, because `Settings` checks the suffix. It authenticates
# nothing: every token below is signed by the key generated here, and the
# verifier is told to trust that key and no other.
CLIENT_ID = "1234567890-testclient.apps.googleusercontent.com"
REDIRECT_URI = "https://app.wasla.test/auth/google/callback"
KID = "endpoint-test-key"
ISSUER = "https://accounts.google.com"

SUBJECT = "109876543210987654321"
GOOGLE_EMAIL = "google-person@example.com"
GOOGLE_NAME = "A Google Person"
GOOGLE_PICTURE = "https://lh3.googleusercontent.com/a/endpoint=s96-c"

_SIGNING_KEY = rsa.generate_private_key(public_exponent=65537, key_size=2048)


def _jwks() -> dict[str, object]:
    jwk = dict(jwt.algorithms.RSAAlgorithm.to_jwk(_SIGNING_KEY.public_key(), as_dict=True))
    jwk.update({"kid": KID, "use": "sig", "alg": "RS256"})
    return {"keys": [jwk]}


def _id_token(*, nonce: str, **overrides: object) -> str:
    """A genuinely signed Google ID token, which the real verifier will check."""
    now = datetime.now(UTC)
    payload: dict[str, object] = {
        "iss": ISSUER,
        "aud": CLIENT_ID,
        "sub": SUBJECT,
        "email": GOOGLE_EMAIL,
        "email_verified": True,
        "name": GOOGLE_NAME,
        "picture": GOOGLE_PICTURE,
        "nonce": nonce,
        "iat": int(now.timestamp()),
        "exp": int((now + timedelta(minutes=5)).timestamp()),
    }
    payload.update(overrides)
    return jwt.encode(payload, _SIGNING_KEY, algorithm="RS256", headers={"kid": KID})


class _FixedKeyRing(GoogleKeyRing):
    """Google's key document, served from memory instead of over the network."""

    async def _fetch(self) -> dict[str, object]:
        return _jwks()


class _Exchange:
    """What Google's token endpoint would have returned.

    A mutable holder rather than a constructor argument, because the token can
    only be minted once the nonce is known - and the nonce is generated by the
    real flow store during the `authorize` request.
    """

    def __init__(self) -> None:
        self.id_token: str | None = None
        self.error: Exception | None = None
        self.calls: list[dict[str, str]] = []


class _StubbedClient(GoogleOAuthClient):
    """The real client, with exactly one method replaced.

    `authorization_url` is inherited and therefore genuinely exercised - the
    scopes, `access_type=online`, the PKCE challenge and the state all come from
    production code. Only `exchange`, which is an HTTPS call to Google, is
    replaced.
    """

    exchange_result = _Exchange()

    async def exchange(self, *, code: str, code_verifier: str) -> str:
        self.exchange_result.calls.append({"code": code, "code_verifier": code_verifier})
        if self.exchange_result.error is not None:
            raise self.exchange_result.error
        assert self.exchange_result.id_token is not None, "the test did not mint a token"
        return self.exchange_result.id_token


class _FlowCommands:
    """Enough Redis for the flow store and the refresh-token store.

    `set(nx=...)` and the MULTI/EXEC `get`+`delete` are the single-use
    guarantees the flow store is built on, so they behave as Redis does rather
    than being waved through.
    """

    def __init__(self) -> None:
        self.values: dict[str, str] = {}
        self.counters: dict[str, int] = {}
        self.expiries: dict[str, int] = {}

    async def set(self, key, value, ex=None, nx=False):
        if nx and key in self.values:
            return None
        self.values[key] = value
        return True

    async def get(self, key):
        return self.values.get(key)

    async def delete(self, key):
        return 1 if self.values.pop(key, None) is not None else 0

    async def exists(self, key):
        return 1 if key in self.values else 0

    async def incr(self, key):
        self.counters[key] = self.counters.get(key, 0) + 1
        return self.counters[key]

    async def expire(self, key, seconds):
        self.expiries[key] = seconds
        return True

    async def rpush(self, key, value):
        return 1

    def pipeline(self, transaction=True):
        return _FlowPipeline(self)


class _FlowPipeline:
    def __init__(self, store: _FlowCommands) -> None:
        self._store = store
        self._queued: list[tuple[str, str]] = []

    async def __aenter__(self):
        return self

    async def __aexit__(self, *_: object):
        return False

    def get(self, key):
        self._queued.append(("get", key))

    def delete(self, key):
        self._queued.append(("delete", key))

    async def execute(self):
        results = []
        for operation, key in self._queued:
            if operation == "get":
                results.append(self._store.values.get(key))
            else:
                results.append(1 if self._store.values.pop(key, None) is not None else 0)
        return results


