#!/usr/bin/env node
/**
 * Generates src/schema.d.ts from the committed openapi.json (FE-0's export, never edited by
 * hand) with openapi-typescript (AC-01). The header records the document's SHA-256 so a
 * regenerated document without regenerated types is caught by a test, not only by CI (AC-02).
 *
 * Options used, recorded for the report:
 *   - default openapi-typescript 7 output (types only: paths, components, operations)
 *   - transform: a file string - OpenAPI 3.1's `contentMediaType` (what FastAPI emits) or 3.0's
 *     `format: binary` - becomes `Blob` (the multipart override the plan's generator spike
 *     noted; openapi-fetch's bodySerializer builds the FormData)
 *   - defaultNonNullable: false - a property with a `default` stays optional unless the schema
 *     lists it as required. openapi-typescript's default (true) would type the envelope's
 *     `details` and `request_id` as always present, which the real bodies are not (FE-0's
 *     413 has neither); FastAPI's output schemas list their always-present fields as required
 *   - no `--immutable`, no `--enum`, no `--root-types`: the client is keyed by path and method
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const documentPath = join(root, "openapi.json");
const outputPath = join(root, "src", "schema.d.ts");

const raw = readFileSync(documentPath);
const sha256 = createHash("sha256").update(raw).digest("hex");

const BLOB = ts.factory.createTypeReferenceNode(ts.factory.createIdentifier("Blob"));
const NULL = ts.factory.createLiteralTypeNode(ts.factory.createNull());

const ast = await openapiTS(JSON.parse(raw.toString("utf8")), {
  defaultNonNullable: false,
  transform(schemaObject) {
    const isFile =
      schemaObject.format === "binary" ||
      (typeof schemaObject.contentMediaType === "string" &&
        (schemaObject.type === "string" ||
          (Array.isArray(schemaObject.type) && schemaObject.type.includes("string"))));
    if (isFile) {
      const nullable = Array.isArray(schemaObject.type) && schemaObject.type.includes("null");
      return nullable ? ts.factory.createUnionTypeNode([BLOB, NULL]) : BLOB;
    }
    return undefined;
  },
});

const header = [
  "/**",
  " * GENERATED by packages/api-client/scripts/generate.mjs from packages/api-client/openapi.json.",
  " * Do not edit: regenerate with `pnpm --filter @wasla/api-client generate`.",
  ` * openapi.json sha256: ${sha256}`,
  " */",
  "",
].join("\n");

const body = astToString(ast).replace(/\r\n/g, "\n");
writeFileSync(outputPath, header + body, { encoding: "utf8" });
console.log(`schema.d.ts written from openapi.json ${sha256.slice(0, 16)}…`);
