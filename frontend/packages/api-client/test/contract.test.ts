import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { describe, expect, it } from "vitest";

import { CLOSE_REASONS, EVENT_TYPES, queryKey, scopePrefix, STREAM_FRAMES } from "../src";
import { typedHandler } from "./msw";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

describe("the generated client matches the committed document (AC-02)", () => {
  it("schema.d.ts records the sha256 of the openapi.json it was generated from", () => {
    const documentHash = createHash("sha256")
      .update(readFileSync(join(root, "openapi.json")))
      .digest("hex");
    const header = readFileSync(join(root, "src", "schema.d.ts"), "utf8").slice(0, 600);
    const recorded = /openapi\.json sha256: ([0-9a-f]{64})/.exec(header)?.[1];
    expect(recorded, "regenerate with: pnpm --filter @wasla/api-client generate").toBe(
      documentHash,
    );
  });

  it("the generated file was not edited by hand after generation (no CRLF, header first)", () => {
    const text = readFileSync(join(root, "src", "schema.d.ts"), "utf8");
    expect(text.startsWith("/**\n * GENERATED by packages/api-client/scripts/generate.mjs")).toBe(
      true,
    );
    expect(text.includes("\r\n")).toBe(false);
  });
});

describe("the stream's frames equal FE-0's event-types.json (AC-04)", () => {
  const exported = JSON.parse(readFileSync(join(root, "event-types.json"), "utf8")) as {
    event_types: string[];
    close_reasons: string[];
    stream_frames: string[];
  };

  it("event types", () => {
    expect([...EVENT_TYPES].sort()).toEqual([...exported.event_types].sort());
  });
  it("close reasons", () => {
    expect([...CLOSE_REASONS].sort()).toEqual([...exported.close_reasons].sort());
  });
  it("control frames", () => {
    expect([...STREAM_FRAMES].sort()).toEqual([...exported.stream_frames].sort());
  });
});

describe("query keys never cross a workspace or a session (PD-06)", () => {
  const a = { workspaceId: "ws-a", sessionGeneration: 1 };
  const b = { workspaceId: "ws-b", sessionGeneration: 1 };
  const aNext = { workspaceId: "ws-a", sessionGeneration: 2 };

  const same = (x: readonly unknown[], y: readonly unknown[]) =>
    JSON.stringify(x) === JSON.stringify(y);

  it("starts with the workspace and the session generation", () => {
    expect(queryKey(a, "conversations", { limit: 20 })).toEqual([
      "ws-a",
      1,
      "conversations",
      { limit: 20 },
    ]);
  });

  it("two workspaces never share a key", () => {
    expect(same(queryKey(a, "conversations"), queryKey(b, "conversations"))).toBe(false);
  });

  it("two session generations never share a key", () => {
    expect(same(queryKey(a, "conversations"), queryKey(aNext, "conversations"))).toBe(false);
  });

  it("the scope prefix matches its own keys only", () => {
    const key = queryKey(a, "conversations");
    expect(same(key.slice(0, 2), scopePrefix(a))).toBe(true);
    expect(same(key.slice(0, 2), scopePrefix(b))).toBe(false);
  });

  it("is independent of parameter order and drops undefined", () => {
    expect(queryKey(a, "x", { b: 1, a: 2, c: undefined })).toEqual(
      queryKey(a, "x", { a: 2, b: 1 }),
    );
  });

  it("refuses a key without a workspace or a generation", () => {
    expect(() => queryKey({ workspaceId: "", sessionGeneration: 1 }, "x")).toThrow();
    expect(() => queryKey({ workspaceId: "w", sessionGeneration: -1 }, "x")).toThrow();
  });
});

describe("MSW handlers are typed by the contract (AC-05)", () => {
  const BASE = "http://api.test";
  it("accepts a declared path, method, status and body", () => {
    expect(typedHandler(BASE, "get", "/api/v1/timezones", 200, [] as never)).toBeDefined();
  });

  it("refuses what the document does not have (checked by tsc, see the @ts-expect-error lines)", () => {
    // @ts-expect-error no such path in the document
    typedHandler(BASE, "get", "/api/v1/no-such-thing", 200, {});
    // @ts-expect-error the path has no DELETE operation
    typedHandler(BASE, "delete", "/api/v1/timezones", 200, []);
    // @ts-expect-error a status the operation does not declare
    typedHandler(BASE, "get", "/api/v1/auth/me", 299, {});
    // @ts-expect-error a body of the wrong shape for a declared status
    typedHandler(BASE, "post", "/api/v1/events/ticket", 201, { not_a_ticket: true });
    expect(true).toBe(true);
  });
});
